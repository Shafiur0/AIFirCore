/**
 * Evaluates whether a user meets the prerequisites to unlock an exercise variation
 * in a Calisthenics Skill Pathway based on their per-exercise performance history
 * and baseline fitness experience.
 */
export function evaluateVariationUnlockStatus(params: {
  pathway: SkillPathway;
  node: SkillPathway["nodes"][number];
  performanceMap: Record<string, UserExercisePerformance>;
  userBaselineLevel: number;
}): {
  unlocked: boolean;
  reason: string;
} {
  if (params.node.stepOrder === 1) {
    return { unlocked: true, reason: "Foundation entry node — unlocked for all users." };
  }

  const previousNode = params.pathway.nodes.find(
    (n) => n.stepOrder === params.node.stepOrder - 1
  );

  if (!previousNode) {
    return { unlocked: true, reason: "No prior prerequisite node required." };
  }

  const prevPerf = params.performanceMap[previousNode.exerciseSlug];

  if (prevPerf) {
    const hasReps = prevPerf.personalBestReps >= params.node.prerequisiteReps;
    const hasForm = prevPerf.rollingFormScore >= params.node.prerequisiteFormScore;

    if (hasReps && hasForm) {
      return {
        unlocked: true,
        reason: `Unlocked via verified ${previousNode.exerciseName} mastery (${prevPerf.personalBestReps} reps @ ${Math.round(prevPerf.rollingFormScore)}% form).`,
      };
    }

    return {
      unlocked: false,
      reason: `Prerequisite required: Achieve ${params.node.prerequisiteReps} reps with >= ${params.node.prerequisiteFormScore}% form on ${previousNode.exerciseName} (current: ${prevPerf.personalBestReps} reps @ ${Math.round(prevPerf.rollingFormScore)}% form).`,
    };
  }

  // If no logged sessions yet on previous node, allow up to user's assessed baseline level (capped at level 2 without logged proof for advanced skills >= level 4)
  if (params.node.level <= 2 && params.userBaselineLevel >= params.node.level) {
    return {
      unlocked: true,
      reason: `Unlocked via onboarding baseline assessment (Level ${params.userBaselineLevel}).`,
    };
  }

  return {
    unlocked: false,
    reason: `Locked: Complete ${params.node.prerequisiteReps} reps of ${previousNode.exerciseName} with >= ${params.node.prerequisiteFormScore}% form score first.`,
  };
}
